/// 设置中的语言选项。`system` 跟随 Windows 语言，明确选择的语言保持不变。
enum AppLanguage { system, zh, en }

extension AppLanguageDetails on AppLanguage {
  /// 将用户语言选择解析成 Locale；跟随系统时读取传入或平台语言，未支持的语言回退英文。
  Locale resolve([Locale? systemLocale]) {
    if (this == AppLanguage.zh) return const Locale('zh');
    if (this == AppLanguage.en) return const Locale('en');
    final Locale locale = systemLocale ?? ui.PlatformDispatcher.instance.locale;
    return locale.languageCode.toLowerCase().startsWith('zh')
        ? const Locale('zh')
        : const Locale('en');
  }
}

